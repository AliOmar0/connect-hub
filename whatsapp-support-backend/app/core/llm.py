        if history is None:
            history = []
            
        dynamic_prompt = SYSTEM_PROMPT
        if session_types:
            types_list = "\n".join([f"- {t['name']}" for t in session_types])
            dynamic_prompt += f"\n\nنطاق الخدمات المصنفة التي يمكنك المساعدة فيها حالياً تشمل:\n{types_list}\nعندما تفهم طلب العميل، حاول توجيهه ضمن أحد هذه المجالات إذا كان ذلك مناسباً."

